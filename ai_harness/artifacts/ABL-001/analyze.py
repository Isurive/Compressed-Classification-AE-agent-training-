"""ABL-001 analysis: sparsity x auxiliary-loss factorial, with GRID-002 full-loss and linear cells.

    python -B ai_harness/artifacts/ABL-001/analyze.py   (from Final Project)

Cells (all Xavier init, ImageNetV2-source top-1, paired by seed):
  full  = GRID-002 grid-xavier sparse/dense (CE + MSE + 0.1 dep + 0.05 coh)
  mse   = ABL-001 abl-mse  (CE + MSE)
  none  = ABL-001 abl-none (CE + 1e-6 MSE ~ CE only)
  linear = GRID-002 linear (wd 1e-4)
Effects (pp, mean +- sd over seeds): sparsity = sparse - dense within a loss; aux = full - none and mse - none within
a head; regularizers = full - mse; width = dense-none (512-2048-1000 MLP) - linear.
"""
import csv
import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
LEVELS = ["source", "L060", "L080", "L090", "L095"]
SEEDS = [42, 43, 44]


def ms(xs):
    return statistics.mean(xs), (statistics.stdev(xs) if len(xs) > 1 else 0.0)


def load():
    cells = defaultdict(dict)  # name -> {(level, seed): top1} on ImageNetV2-source
    digests = defaultdict(set)
    sources = [(ROOT / "runs/GRID-002/results.csv", {"grid-xavier": "full"}),
               (ROOT / "runs/ABL-001/results.csv", {"abl-mse": "mse", "abl-none": "none"})]
    for path, phases in sources:
        for r in csv.DictReader(open(path, encoding="utf-8")):
            if r["eval_level"] != "source" or r["phase"] not in phases:
                continue
            loss = phases[r["phase"]]
            name = "linear" if r["model"] == "linear" else f"{r['model']}-{loss}"
            cells[name][(r["train_level"], int(r["seed"]))] = float(r["top1"])
            digests[int(r["seed"])].add(r["split_digest"])
    return cells, digests


def main():
    cells, digests = load()
    names = ["sparse-full", "dense-full", "sparse-mse", "dense-mse", "sparse-none", "dense-none", "linear"]
    acc = {n: {lv: ms([cells[n][(lv, s)] for s in SEEDS]) for lv in LEVELS} for n in names}
    drop = {n: {lv: ms([cells[n][("source", s)] - cells[n][(lv, s)] for s in SEEDS]) for lv in LEVELS[1:]} for n in names}

    def diff(a, b):
        return {lv: ms([cells[a][(lv, s)] - cells[b][(lv, s)] for s in SEEDS]) for lv in LEVELS}

    effects = {
        "sparsity | full loss (sparse-full - dense-full)": diff("sparse-full", "dense-full"),
        "sparsity | MSE only (sparse-mse - dense-mse)": diff("sparse-mse", "dense-mse"),
        "sparsity | no aux (sparse-none - dense-none)": diff("sparse-none", "dense-none"),
        "MSE aux | sparse (sparse-mse - sparse-none)": diff("sparse-mse", "sparse-none"),
        "MSE aux | dense (dense-mse - dense-none)": diff("dense-mse", "dense-none"),
        "dep+coh | sparse (sparse-full - sparse-mse)": diff("sparse-full", "sparse-mse"),
        "dep+coh | dense (dense-full - dense-mse)": diff("dense-full", "dense-mse"),
        "width | MLP vs linear (dense-none - linear)": diff("dense-none", "linear"),
        "whole method vs linear (sparse-full - linear)": diff("sparse-full", "linear"),
    }
    signs = {k: {lv: sum((cells[a][(lv, s)] - cells[b][(lv, s)]) > 0 for s in SEEDS)
                 for lv in LEVELS}
             for k, (a, b) in zip(effects, [("sparse-full", "dense-full"), ("sparse-mse", "dense-mse"),
                                           ("sparse-none", "dense-none"), ("sparse-mse", "sparse-none"),
                                           ("dense-mse", "dense-none"), ("sparse-full", "sparse-mse"),
                                           ("dense-full", "dense-mse"), ("dense-none", "linear"),
                                           ("sparse-full", "linear")])}
    pooled = {k: ms([v[lv][0] for lv in LEVELS])[0] for k, v in effects.items()}
    same = all(len(d) == 1 for d in digests.values())
    out = {"splits_consistent": same, "digests": {s: sorted(d) for s, d in digests.items()},
           "accuracy": acc, "drop": drop, "effects": effects, "positive_seeds": signs, "mean_over_levels": pooled}
    (HERE / "analysis.json").write_text(json.dumps(out, indent=2), encoding="utf-8")

    p = lambda v: f"{100 * v[0]:.2f} ± {100 * v[1]:.2f}"  # noqa: E731
    L = ["# ABL-001 analysis (generated by analyze.py)", "",
         f"One split digest per seed across GRID-002 and ABL-001: **{same}**. ImageNetV2-source top-1 %, mean ± sd over seeds 42-44.", "",
         "## Accuracy", "", "| Cell | " + " | ".join(LEVELS) + " |", "| --- |" + " --- |" * len(LEVELS)]
    for n in names:
        L.append(f"| {n} | " + " | ".join(p(acc[n][lv]) for lv in LEVELS) + " |")
    L += ["", "## Paired drop vs the same cell on source (pp)", "", "| Cell | " + " | ".join(LEVELS[1:]) + " |",
          "| --- |" + " --- |" * len(LEVELS[1:])]
    for n in names:
        L.append(f"| {n} | " + " | ".join(p(drop[n][lv]) for lv in LEVELS[1:]) + " |")
    L += ["", "## Effects (pp, paired by seed; in brackets: seeds with a positive difference, of 3)", "",
          "| Effect | " + " | ".join(LEVELS) + " | mean over levels |", "| --- |" + " --- |" * (len(LEVELS) + 1)]
    for k, v in effects.items():
        L.append(f"| {k} | " + " | ".join(f"{p(v[lv])} [{signs[k][lv]}]" for lv in LEVELS) + f" | {100 * pooled[k]:.2f} |")
    (HERE / "analysis.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
