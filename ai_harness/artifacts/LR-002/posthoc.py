"""LR-002 post-hoc (NOT pre-registered) numbers quoted in report.md; added in revision 1 (REVIEW-009 O-1, S-1).

    python -B ai_harness/artifacts/LR-002/posthoc.py   (from Final Project; standard library only)

Validation only, same cells as the pre-registered analysis (source/L090 x seeds 42-44), selected on the same cells.
Selection within a budget n: epoch <= n with the highest validation top-1, then lower CE.
Writes posthoc.md next to this file. Does not change analyze.py or its outputs.
"""
import json
import math
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
CELLS = [(lv, s) for lv in ("source", "L090") for s in (42, 43, 44)]
T975 = 2.5706


def lr_name(lr):
    return f"lr{lr:.0e}".replace("e-0", "e-")


def select(history, n):
    return max((e for e in history if e["epoch"] <= n), key=lambda e: (e["val_top1"], -e["val_ce"]))


def cells(task, head, lr, n):
    out = []
    for lv, s in CELLS:
        d = json.loads((ROOT / "runs" / task / head / lr_name(lr) / lv / f"seed{s}" / "done.json").read_text())
        out.append(select(d["history"], n)["val_top1"])
    return out


def last(task, head, lr, epoch):
    out = []
    for lv, s in CELLS:
        d = json.loads((ROOT / "runs" / task / head / lr_name(lr) / lv / f"seed{s}" / "done.json").read_text())
        out.append(next(e for e in d["history"] if e["epoch"] == epoch)["val_top1"])
    return out


def gap(a, b):
    x = [100 * (i - j) for i, j in zip(a, b)]
    m = statistics.mean(x)
    h = T975 * statistics.stdev(x) / math.sqrt(len(x))
    return f"{m:+.2f} [{m - h:+.2f}, {m + h:+.2f}] {sum(v > 0 for v in x)}/6"


def main():
    S = {  # (label, values)
        "sparse M2048 3e-4@10 (adopted)": cells("LR-001", "sparse-M2048", 3e-4, 10),
        "sparse M2048 1e-4@20": cells("LR-002", "sparse-M2048", 1e-4, 20),
        "sparse M2048 1e-4@10": cells("LR-002", "sparse-M2048", 1e-4, 10),
        "sparse M4096 1e-4@10 (adopted)": cells("LR-002", "sparse-M4096", 1e-4, 10),
        "sparse M4096 1e-4@20": cells("LR-002", "sparse-M4096", 1e-4, 20),
        "dense M2048 1e-4@10 (adopted)": cells("LR-002", "dense-M2048", 1e-4, 10),
        "dense M2048 1e-4@20": cells("LR-002", "dense-M2048", 1e-4, 20),
        "linear 3e-4@20 (adopted)": cells("LR-002", "linear", 3e-4, 20),
        "linear 3e-4@10": cells("LR-002", "linear", 3e-4, 10),
        "sparse M2048 1e-3@10": cells("LR-001", "sparse-M2048", 1e-3, 10),
        "linear 1e-3@10": cells("LR-002", "linear", 1e-3, 10),
    }
    rows = [
        ("Adopted settings (unequal budgets: dictionary 10 ep, linear 20 ep)", [
            ("sparse M2048 - linear", "sparse M2048 3e-4@10 (adopted)", "linear 3e-4@20 (adopted)"),
            ("dense M2048 - linear", "dense M2048 1e-4@10 (adopted)", "linear 3e-4@20 (adopted)"),
            ("sparse M4096 - linear", "sparse M4096 1e-4@10 (adopted)", "linear 3e-4@20 (adopted)"),
            ("sparse M2048 - dense M2048", "sparse M2048 3e-4@10 (adopted)", "dense M2048 1e-4@10 (adopted)"),
            ("sparse M4096 - sparse M2048", "sparse M4096 1e-4@10 (adopted)", "sparse M2048 3e-4@10 (adopted)")]),
        ("Equal 10-epoch budget", [
            ("sparse M2048 3e-4 - linear 3e-4", "sparse M2048 3e-4@10 (adopted)", "linear 3e-4@10"),
            ("dense M2048 1e-4 - linear 3e-4", "dense M2048 1e-4@10 (adopted)", "linear 3e-4@10"),
            ("sparse M4096 1e-4 - sparse M2048 1e-4", "sparse M4096 1e-4@10 (adopted)", "sparse M2048 1e-4@10")]),
        ("Equal 20-epoch budget (each head's best candidate at 20 epochs)", [
            ("sparse M2048 1e-4 - linear 3e-4", "sparse M2048 1e-4@20", "linear 3e-4@20 (adopted)"),
            ("dense M2048 1e-4 - linear 3e-4", "dense M2048 1e-4@20", "linear 3e-4@20 (adopted)"),
            ("sparse M2048 - dense M2048 (both 1e-4)", "sparse M2048 1e-4@20", "dense M2048 1e-4@20"),
            ("sparse M4096 - sparse M2048 (both 1e-4)", "sparse M4096 1e-4@20", "sparse M2048 1e-4@20")]),
        ("Old setting (lr 1e-3, 10 epochs), for reference", [
            ("sparse M2048 - linear", "sparse M2048 1e-3@10", "linear 1e-3@10")]),
    ]
    L = ["# LR-002 post-hoc numbers (generated by posthoc.py; NOT pre-registered; validation only)", "",
         "Paired by cell (source/L090 x seeds 42-44), mean [95% CI, df 5], cells positive. Selected on the same cells.", ""]
    for title, items in rows:
        L += [f"## {title}", "", "| Gap (pp) | value |", "| --- | --- |"]
        L += [f"| {name} | {gap(S[a], S[b])} |" for name, a, b in items]
        L.append("")
    L += ["## No checkpoint selection", "", "| Gap (pp) | value |", "| --- | --- |",
          f"| sparse M2048 3e-4 epoch 10 - linear 3e-4 epoch 20 | "
          f"{gap(last('LR-001', 'sparse-M2048', 3e-4, 10), last('LR-002', 'linear', 3e-4, 20))} |", ""]
    L += ["## Per-level means at the adopted settings (%)", "", "| Head | source | L090 | drop |", "| --- | --- | --- | --- |"]
    for k in ("sparse M2048 3e-4@10 (adopted)", "sparse M4096 1e-4@10 (adopted)", "dense M2048 1e-4@10 (adopted)",
              "linear 3e-4@20 (adopted)"):
        src, l90 = statistics.mean(S[k][:3]), statistics.mean(S[k][3:])
        L.append(f"| {k} | {100 * src:.2f} | {100 * l90:.2f} | {100 * (src - l90):.2f} |")
    L += ["", "## Linear head: mean validation top-1 by epoch (no selection)", "", "| lr | epochs 10-20 |", "| --- | --- |"]
    for lr in (3e-4, 1e-4):
        L.append(f"| {lr:g} | " + ", ".join(f"{100 * statistics.mean(last('LR-002', 'linear', lr, e)):.2f}"
                                             for e in range(10, 21)) + " |")
    (HERE / "posthoc.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
