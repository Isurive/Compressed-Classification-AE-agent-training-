"""GRID-002 analysis: Xavier-init heads vs GRID-001 inherited-fc heads, on ImageNetV2.

    python -B ai_harness/artifacts/GRID-002/analyze.py   (from Final Project)

Reads runs/GRID-002/results.csv and runs/GRID-001/results.csv (grid rows only). Writes analysis.md and
analysis.json next to this file. Same pre-declared rules as GRID-001: paired drop vs the same model trained
on source, 1.0 pp tolerance on the mean drop; differences under about 1 pp are inconclusive with 3 seeds.
"""
import csv
import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]  # REVIEW-002 copy: five levels up to the project root
HERE = Path(__file__).resolve().parent
LEVELS = ["source", "L020", "L060", "L080", "L085", "L090", "L095", "L100"]
MODELS = ["sparse", "dense", "linear"]
TOL = 0.010


def ms(xs):
    return statistics.mean(xs), (statistics.stdev(xs) if len(xs) > 1 else 0.0)


def load(path, phase):
    acc = defaultdict(dict)  # (model, eval) -> {(level, seed): top1}
    digests = defaultdict(set)
    meta = {}
    for r in csv.DictReader(open(path, encoding="utf-8")):
        if r["phase"] != phase:
            continue
        kind = "source" if r["eval_level"] == "source" else "matched"
        acc[(r["model"], kind)][(r["train_level"], int(r["seed"]))] = float(r["top1"])
        digests[int(r["seed"])].add(r["split_digest"])
        meta[r["model"]] = {k: r[k] for k in ("atoms", "k", "fc_init", "weight_decay")}
        if kind == "source":
            meta.setdefault(("best_epoch", r["model"]), []).append(int(r["best_epoch"]))
    return acc, digests, meta


def table(acc, model):
    t = acc[(model, "source")]
    seeds = sorted({s for _, s in t})
    out = {}
    for level in LEVELS:
        if not all((level, s) in t for s in seeds):
            continue
        a = [t[(level, s)] for s in seeds]
        e = {"mean": ms(a)[0], "sd": ms(a)[1], "n": len(a)}
        if level != "source":
            d = [t[("source", s)] - t[(level, s)] for s in seeds]
            e["drop"], e["drop_sd"] = ms(d)
            e["retains_1pp"] = e["drop"] <= TOL
        m = acc[(model, "matched")]
        if level != "source" and all((level, s) in m for s in seeds):
            e["matched_mean"] = ms([m[(level, s)] for s in seeds])[0]
        out[level] = e
    return out, seeds


def paired(acc_a, model_a, acc_b, model_b, seeds):
    """Per level: mean/sd of A(a) - A(b) and of drop(b) - drop(a) (positive -> a retained more)."""
    a, b = acc_a[(model_a, "source")], acc_b[(model_b, "source")]
    res = {}
    for level in LEVELS:
        if not all((level, s) in a and (level, s) in b for s in seeds):
            continue
        gap = [a[(level, s)] - b[(level, s)] for s in seeds]
        e = {"gap": ms(gap)[0], "gap_sd": ms(gap)[1]}
        if level != "source":
            inter = [(b[("source", s)] - b[(level, s)]) - (a[("source", s)] - a[(level, s)]) for s in seeds]
            e["interaction"], e["interaction_sd"] = ms(inter)
        res[level] = e
    return res


def main():
    x, dx, mx = load(ROOT / "runs/GRID-002/results.csv", "grid-xavier")
    o, do, mo = load(ROOT / "runs/GRID-001/results.csv", "grid")
    same_splits = all(dx[s] == do[s] and len(dx[s]) == 1 for s in dx)
    result = {"splits_match_grid001": same_splits, "settings_xavier": {m: mx[m] for m in MODELS if m in mx},
              "best_epochs_xavier": {m: mx.get(("best_epoch", m)) for m in MODELS},
              "xavier": {}, "inherited": {}, "sparse_vs": {}, "xavier_minus_inherited": {}}
    seeds = None
    for m in MODELS:
        result["xavier"][m], seeds = table(x, m)
        result["inherited"][m], _ = table(o, m)
        result["xavier_minus_inherited"][m] = paired(x, m, o, m, seeds)
    for other in ("dense", "linear"):
        result["sparse_vs"][other] = paired(x, "sparse", x, other, seeds)
    ref = {r["eval_level"]: r["top1"] for r in json.loads((ROOT / "runs/GRID-001/reference_original_fc.json").read_text())}
    result["original_fc_v2_source"] = ref["source"]
    (HERE / "analysis.json").write_text(json.dumps(result, indent=2, default=str), encoding="utf-8")

    p = lambda v: f"{100 * v:.2f}"  # noqa: E731
    L = ["# GRID-002 analysis (generated by analyze.py)", "",
         f"Splits identical to GRID-001 per seed: **{same_splits}**. Seeds: {seeds}. "
         f"Original ImageNet fc on ImageNetV2-source: {p(ref['source'])}%.", "",
         "## ImageNetV2-source top-1 % (mean ± sd), paired drop vs the same model on source", "",
         "| Level | " + " | ".join(f"{m} xavier | drop" for m in MODELS) + " |",
         "| --- |" + " --- | --- |" * len(MODELS)]
    for level in LEVELS:
        cells = []
        for m in MODELS:
            e = result["xavier"][m].get(level)
            cells += [f"{p(e['mean'])} ± {p(e['sd'])}", f"{p(e['drop'])} ± {p(e['drop_sd'])}" if "drop" in e else "—"]
        L.append(f"| {level} | " + " | ".join(cells) + " |")
    L += ["", "## Tolerance (mean drop ≤ 1.0 pp)", "", "| Model | strongest passing level | first failing level |", "| --- | --- | --- |"]
    for m in MODELS:
        passing = [lv for lv in LEVELS[1:] if result["xavier"][m][lv]["retains_1pp"]]
        failing = [lv for lv in LEVELS[1:] if not result["xavier"][m][lv]["retains_1pp"]]
        L.append(f"| {m} | {passing[-1] if passing else 'none'} | {failing[0] if failing else 'none'} |")
    L += ["", "## Sparse vs other Xavier heads (pp): absolute gap sparse − other; interaction drop(other) − drop(sparse)", "",
          "| Level | gap vs dense | interaction vs dense | gap vs linear | interaction vs linear |", "| --- | --- | --- | --- | --- |"]
    for level in LEVELS:
        d, l = result["sparse_vs"]["dense"][level], result["sparse_vs"]["linear"][level]
        f = lambda e, k: f"{p(e[k])} ± {p(e[k + '_sd'])}" if k in e else "—"  # noqa: E731
        L.append(f"| {level} | {f(d, 'gap')} | {f(d, 'interaction')} | {f(l, 'gap')} | {f(l, 'interaction')} |")
    L += ["", "## Xavier minus inherited-fc (GRID-001), same model, paired by seed (pp)", "",
          "| Level | " + " | ".join(f"{m} gap" for m in MODELS) + " |", "| --- |" + " --- |" * len(MODELS)]
    for level in LEVELS:
        L.append(f"| {level} | " + " | ".join(
            f"{p(result['xavier_minus_inherited'][m][level]['gap'])} ± {p(result['xavier_minus_inherited'][m][level]['gap_sd'])}"
            for m in MODELS) + " |")
    L += ["", "## Matched-level test (ImageNetV2 compressed like training; secondary)", "",
          "| Level | " + " | ".join(MODELS) + " |", "| --- |" + " --- |" * len(MODELS)]
    for level in LEVELS[1:]:
        L.append(f"| {level} | " + " | ".join(p(result["xavier"][m][level]["matched_mean"]) for m in MODELS) + " |")
    L += ["", f"Best epochs (Xavier, per run): {json.dumps(result['best_epochs_xavier'])}"]
    (HERE / "analysis.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
