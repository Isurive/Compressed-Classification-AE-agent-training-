"""SEED-001 analysis, implementing the rule pre-registered in task.json.

    python -B ai_harness/artifacts/SEED-001/analyze.py   (from Final Project)

Primary: new seeds 45-51 (runs/SEED-001). Secondary: seeds 42-51, adding seeds 42-44 from ABL-001 `abl-mse`
(sparse, dense) and GRID-002 `grid-xavier` (linear), which used identical settings.
Metric: ImageNetV2-source top-1. Paired differences per seed; mean, sd, two-sided paired t 95% CI, sign count.
'Detected' = CI excludes 0. 'Meaningful' = detected and mean >= 1.0 pp.
Writes analysis.md / analysis.json next to this file (copy the script elsewhere to experiment).
"""
import csv
import json
import math
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
LEVELS = ["source", "L080", "L090"]
NEW, OLD = list(range(45, 52)), [42, 43, 44]
T975 = {2: 4.303, 6: 2.447, 9: 2.262}  # two-sided 95% Student t quantiles by df
TOL = 0.010


def load():
    acc = defaultdict(dict)  # model -> {(level, seed): top1}
    digests = defaultdict(set)
    sources = [(ROOT / "runs/SEED-001/results.csv", {"seed-mse", "seed-linear"}),
               (ROOT / "runs/ABL-001/results.csv", {"abl-mse"}),
               (ROOT / "runs/GRID-002/results.csv", {"grid-xavier"})]
    for path, phases in sources:
        for r in csv.DictReader(open(path, encoding="utf-8")):
            if r["phase"] not in phases or r["eval_level"] != "source" or r["train_level"] not in LEVELS:
                continue
            if r["phase"] == "grid-xavier" and r["model"] != "linear":
                continue
            acc[r["model"]][(r["train_level"], int(r["seed"]))] = float(r["top1"])
            digests[int(r["seed"])].add(r["split_digest"])
    return acc, digests


def stats(diffs):
    n = len(diffs)
    m, sd = statistics.mean(diffs), statistics.stdev(diffs)
    half = T975[n - 1] * sd / math.sqrt(n)
    return {"n": n, "mean": m, "sd": sd, "ci_low": m - half, "ci_high": m + half,
            "positive": sum(d > 0 for d in diffs), "detected": (m - half) > 0 or (m + half) < 0,
            "meaningful": ((m - half) > 0 or (m + half) < 0) and abs(m) >= TOL, "diffs": diffs}


def compare(acc, a, b, seeds):
    out = {}
    for level in LEVELS:
        out[level] = stats([acc[a][(level, s)] - acc[b][(level, s)] for s in seeds])
    out["pooled"] = stats([statistics.mean(acc[a][(lv, s)] - acc[b][(lv, s)] for lv in LEVELS) for s in seeds])
    return out


def main():
    acc, digests = load()
    one_split = {s: len(d) == 1 for s, d in digests.items()}
    distinct = len({next(iter(digests[s])) for s in NEW + OLD if digests[s]}) == len(NEW + OLD)
    pairs = [("sparse", "dense"), ("sparse", "linear"), ("dense", "linear")]
    res = {"one_split_digest_per_seed": all(one_split.values()), "splits_distinct_across_seeds": distinct,
           "accuracy": {m: {lv: {g: statistics.mean(acc[m][(lv, s)] for s in seeds)
                                 for g, seeds in (("new", NEW), ("all", OLD + NEW))} for lv in LEVELS}
                        for m in ("sparse", "dense", "linear")},
           "primary_new_seeds": {f"{a}-{b}": compare(acc, a, b, NEW) for a, b in pairs},
           "secondary_all_seeds": {f"{a}-{b}": compare(acc, a, b, OLD + NEW) for a, b in pairs}}
    (HERE / "analysis.json").write_text(json.dumps(res, indent=2), encoding="utf-8")

    p = lambda v: f"{100 * v:.2f}"  # noqa: E731
    L = ["# SEED-001 analysis (generated by analyze.py)", "",
         f"One split digest per seed: **{res['one_split_digest_per_seed']}**. "
         f"Splits distinct across seeds 42-51: **{distinct}**. Metric: ImageNetV2-source top-1 (%).", "",
         "## Mean accuracy", "", "| Model | " + " | ".join(f"{lv} (new 7) | {lv} (all 10)" for lv in LEVELS) + " |",
         "| --- |" + " --- |" * (2 * len(LEVELS))]
    for m in ("sparse", "dense", "linear"):
        L.append(f"| {m} | " + " | ".join(f"{p(res['accuracy'][m][lv]['new'])} | {p(res['accuracy'][m][lv]['all'])}"
                                         for lv in LEVELS) + " |")
    for title, key in (("PRIMARY: new seeds 45-51 (n = 7, df = 6)", "primary_new_seeds"),
                       ("SECONDARY: all seeds 42-51 (n = 10, df = 9)", "secondary_all_seeds")):
        L += ["", f"## {title}", "",
              "| Comparison | Level | Mean diff (pp) | sd | 95% CI | positive seeds | detected | meaningful (≥ 1 pp) |",
              "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        for comp, by_level in res[key].items():
            for lv, e in by_level.items():
                L.append(f"| {comp} | {lv} | {p(e['mean'])} | {p(e['sd'])} | [{p(e['ci_low'])}, {p(e['ci_high'])}] | "
                         f"{e['positive']}/{e['n']} | {'yes' if e['detected'] else 'no'} | {'yes' if e['meaningful'] else 'no'} |")
    (HERE / "analysis.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
